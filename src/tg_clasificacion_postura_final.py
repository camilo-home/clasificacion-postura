def evaluate_ml_model(
    model,
    model_name,
    X_train,
    X_test,
    y_train,
    y_test
):

    # ======================================================
    # ENTRENAMIENTO
    # ======================================================

    model.fit(
        X_train,
        y_train
    )

    # ======================================================
    # PREDICCIONES
    # ======================================================

    y_pred_train = model.predict(
        X_train
    )

    y_pred_test = model.predict(
        X_test
    )

    # ======================================================
    # ACCURACY
    # ======================================================

    train_acc = accuracy_score(
        y_train,
        y_pred_train
    )

    test_acc = accuracy_score(
        y_test,
        y_pred_test
    )

