"""## Funciones geométricas"""

def calcular_angulo(a, b, c):

    ba = a - b
    bc = c - b

    cos_angle = np.dot(ba, bc) / (
        np.linalg.norm(ba) *
        np.linalg.norm(bc) + 1e-6
    )

    angle = np.arccos(
        np.clip(cos_angle, -1.0, 1.0)
    )

    return np.degrees(angle)

def calcular_simetria(p1, p2):

    return np.linalg.norm(p1 - p2)

