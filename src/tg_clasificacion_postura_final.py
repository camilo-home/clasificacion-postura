def normalize_skeleton(row):

    coords = row.values.reshape(-1,3)

    center = coords.mean(axis=0)

    coords = coords - center

    scale = np.linalg.norm(
        coords[0] - coords[-1]
    )

    if scale < 1e-6:
        scale = 1e-6

    coords = coords / scale

    return coords.flatten()

