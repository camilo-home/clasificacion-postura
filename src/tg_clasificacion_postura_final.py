# FEATURES FRONTALES

def extraer_features_frontales(row):

    coords = row.values.reshape(-1,3)

    if ejercicio == "peso muerto":

        shoulder_l, shoulder_r, elbow_l, elbow_r, hand_l, hand_r,hip_l, hip_r, knee_l, knee_r = coords

        shoulder_sym = calcular_simetria(
            shoulder_l,
            shoulder_r
        )

        hip_sym = calcular_simetria(
            hip_l,
            hip_r
        )

        knee_sym = calcular_simetria(
            knee_l,
            knee_r
        )

        shoulder_height_diff = abs(
            shoulder_l[1] - shoulder_r[1]
        )

        hip_height_diff = abs(
            hip_l[1] - hip_r[1]
        )

        knee_height_diff = abs(
            knee_l[1] - knee_r[1]
        )

        hand_height_diff = abs(
            hand_l[1] - hand_r[1]
        )

        shoulder_tilt = np.degrees(
            np.arctan2(
                shoulder_r[1]-shoulder_l[1],
                shoulder_r[0]-shoulder_l[0]
            )
        )

        hip_tilt = np.degrees(
            np.arctan2(
                hip_r[1]-hip_l[1],
                hip_r[0]-hip_l[0]
            )
        )

        bar_tilt = np.degrees(
            np.arctan2(
                hand_r[1]-hand_l[1],
                hand_r[0]-hand_l[0]
            )
        )

        arm_left = np.linalg.norm(
            shoulder_l - hand_l
        )

        arm_right = np.linalg.norm(
            shoulder_r - hand_r
        )


        arm_asymmetry = abs(
            arm_left - arm_right
        )

        leg_left = np.linalg.norm(
            hip_l - knee_l
        )

        leg_right = np.linalg.norm(
            hip_r - knee_r
        )

        leg_asymmetry = abs(
            leg_left - leg_right
        )

        center_shoulders = (
            shoulder_l + shoulder_r
        ) / 2

        center_hips = (
            hip_l + hip_r
        ) / 2

        lateral_shift = abs(
            center_shoulders[0]
            -
            center_hips[0]
        )

        return np.array([

            shoulder_sym,

            hip_sym,

            knee_sym,

            shoulder_height_diff,

            hip_height_diff,

            knee_height_diff,

            hand_height_diff,

            shoulder_tilt,

            hip_tilt,

            bar_tilt,

            arm_asymmetry,

            leg_asymmetry,

            lateral_shift

        ])


    elif ejercicio == "sentadilla":

        shoulder_l, shoulder_r, elbow_l, elbow_r, hand_l, hand_r,hip_l, hip_r, knee_l, knee_r = coords

        shoulder_sym = calcular_simetria(
            shoulder_l,
            shoulder_r
        )

        hip_sym = calcular_simetria(
            hip_l,
            hip_r
        )

        knee_sym = calcular_simetria(
            knee_l,
            knee_r
        )

        knee_height_diff = abs(
            knee_l[1] - knee_r[1]
        )

        hip_height_diff = abs(
            hip_l[1] - hip_r[1]
        )

        shoulder_height_diff = abs(
            shoulder_l[1] - shoulder_r[1]
        )

        shoulder_tilt = np.degrees(
            np.arctan2(
                shoulder_r[1]-shoulder_l[1],
                shoulder_r[0]-shoulder_l[0]
            )
        )

        hip_tilt = np.degrees(
            np.arctan2(
                hip_r[1]-hip_l[1],
                hip_r[0]-hip_l[0]
            )
        )

        knee_hip_l = np.linalg.norm(
            knee_l - hip_l
        )

        knee_hip_r = np.linalg.norm(
            knee_r - hip_r
        )

        depth_diff = abs(
            knee_hip_l -
            knee_hip_r
        )


        return np.array([
            shoulder_sym,

            hip_sym,

            knee_sym,

            shoulder_height_diff,

            hip_height_diff,

            knee_height_diff,

            shoulder_tilt,

            hip_tilt,

            depth_diff

        ])


    elif ejercicio in [
        "curl biceps",
        "press banca"
    ]:

        shoulder_l, shoulder_r, elbow_l, elbow_r, wrist_l, wrist_r = coords

        shoulder_sym = calcular_simetria(
            shoulder_l,
            shoulder_r
        )

        elbow_sym = calcular_simetria(
            elbow_l,
            elbow_r
        )

        wrist_sym = calcular_simetria(
            wrist_l,
            wrist_r
        )

        wrist_height_diff = abs(
            wrist_l[1] - wrist_r[1]
        )

        ang_left = calcular_angulo(
            shoulder_l,
            elbow_l,
            wrist_l
        )

        ang_right = calcular_angulo(
            shoulder_r,
            elbow_r,
            wrist_r
        )

        angle_diff = abs(
            ang_left - ang_right
        )

        return np.array([
            shoulder_sym,
            elbow_sym,
            wrist_sym,
            wrist_height_diff,
            angle_diff
        ])

